"""Export guan_route (+ guan_route_elevation) as a static Elm data module,
for the 3D route view.

One Segment per stop_order, in EPSG:2263 (NY State Plane feet) so x/y are in
the same unit as z (elevation, feet). Translated so coordinates sit near the
origin (same bounding-box-min convention as export_guan_route_svg.py, but no
Y-flip — this isn't SVG). Elevation is raw feet; exaggeration is applied at
render time in Main.elm, not baked in here.

Usage:
    uv run scripts/export_guan_route_elm.py [output.elm]
"""
import sys
from pathlib import Path

import psycopg

DB = "dbname=green_wood_guan host=127.0.0.1 port=5432"
PRECISION = 2
DEFAULT_OUT = Path(__file__).parent.parent / "elm" / "src" / "GuanRoute.elm"


def fmt(n):
    return f"{n:.{PRECISION}f}"


def elm_string(s):
    escaped = s.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def main():
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT

    with psycopg.connect(DB) as conn:
        with conn.cursor() as cur:
            cur.execute("""
                SELECT ST_XMin(ext), ST_YMin(ext)
                FROM (
                    SELECT ST_Extent(ST_Transform(the_geog::geometry, 2263)) AS ext
                    FROM guan_route
                ) e
            """)
            min_x, min_y = cur.fetchone()

            cur.execute(
                """
                SELECT
                    g.stop_order,
                    g.is_retrace,
                    g.name,
                    g.from_vertex,
                    ST_X(ST_Transform(g.start_point::geometry, 2263)) - %(min_x)s AS from_x,
                    ST_Y(ST_Transform(g.start_point::geometry, 2263)) - %(min_y)s AS from_y,
                    e.from_elevation_ft,
                    g.to_vertex,
                    ST_X(ST_Transform(g.end_point::geometry, 2263)) - %(min_x)s AS to_x,
                    ST_Y(ST_Transform(g.end_point::geometry, 2263)) - %(min_y)s AS to_y,
                    e.to_elevation_ft
                FROM guan_route g
                JOIN guan_route_elevation e ON e.stop_order = g.stop_order
                ORDER BY g.stop_order
                """,
                {"min_x": min_x, "min_y": min_y},
            )
            rows = cur.fetchall()

    lines = []
    for stop_order, is_retrace, name, from_id, from_x, from_y, from_z, to_id, to_x, to_y, to_z in rows:
        elm_bool = "True" if is_retrace else "False"
        elm_name = f"Just {elm_string(name)}" if name is not None else "Nothing"
        lines.append(
            "{ from = { id = "
            f"{from_id}, x = {fmt(from_x)}, y = {fmt(from_y)}, z = {fmt(from_z)} }}"
            ", to = { id = "
            f"{to_id}, x = {fmt(to_x)}, y = {fmt(to_y)}, z = {fmt(to_z)} }}"
            f", isRetrace = {elm_bool}"
            f", name = {elm_name} }}"
        )

    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        f.write("module GuanRoute exposing (Point, Segment, segments)\n\n\n")
        f.write("-- Generated by scripts/export_guan_route_elm.py — do not edit by hand.\n")
        f.write("--\n")
        f.write("-- Coordinates are in feet (EPSG:2263, NY State Plane Long Island),\n")
        f.write("-- translated so the route's bounding box starts near the origin.\n")
        f.write("-- z is raw elevation in feet, not exaggerated.\n\n\n")
        f.write("type alias Point =\n")
        f.write("    { id : Int, x : Float, y : Float, z : Float }\n\n\n")
        f.write("type alias Segment =\n")
        f.write("    { from : Point, to : Point, isRetrace : Bool, name : Maybe String }\n\n\n")
        f.write("segments : List Segment\n")
        f.write("segments =\n")
        f.write("    [ " + "\n    , ".join(lines) + "\n    ]\n")

    print(f"wrote {len(rows)} segments to {out_path}")


if __name__ == "__main__":
    main()
